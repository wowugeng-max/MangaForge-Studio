export function scanAuthorialForecastRisks(text: string) {
  const lines = String(text || '').split(/\r?\n/)
  const firstContentLine = lines.findIndex(line => String(line || '').trim())
  const hits: Array<{ gate: 'G'; pattern: string; status: 'warn'; evidence: string; fix: string; line: number }> = []
  lines.forEach((line, index) => {
    if (index === firstContentLine && isLikelyChapterTitleLine(line)) return
    const evidence = String(line || '').trim()
    if (!evidence) return
    for (const item of OH_STORY_AUTHORIAL_FORECAST_PATTERNS) {
      item.regex.lastIndex = 0
      if (!item.regex.test(evidence)) continue
      hits.push({
        gate: 'G',
        pattern: item.pattern,
        status: 'warn',
        evidence,
        fix: item.fix,
        line: index + 1,
      })
    }
  })
  return hits
}
